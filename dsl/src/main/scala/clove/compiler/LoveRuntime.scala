package clove.compiler

import clove.ast.*

import clove.dsl.World

object LoveRuntime:

  def wrap(world: World, update: Script): String =
    val regionTable = world.regions.map { r =>
      val overrides = r.handlers.flatMap(_.handles).map { (k, v) =>
        s"    ${k.toLowerCase} = ${LuaEmitter.emitExpr(v)}"
      }.mkString(",\n")
      s"""  {x = ${r.x}, y = ${r.y}, w = ${r.w}, h = ${r.h}, r = ${r.colorR}, g = ${r.colorG}, b = ${r.colorB},
        |$overrides
        |  }""".stripMargin
    }.mkString(",\n")

    s"""-- Generated by Clove

local entities = {}

local regions = {
$regionTable
}

local function checkCollision(a, b)
  if not a or not b then return false end
  return a.x < b.x + b.width and
         a.x + a.width > b.x and
         a.y < b.y + b.height and
         a.y + a.height > b.y
end

local function insideRegion(e, x, y, w, h)
  if not e then return false end
  return e.x < x + w and
         e.x + e.width > x and
         e.y < y + h and
         e.y + e.height > y
end

local handler = {
  gravity = 9.8,

  spawn = function(name, withGravity)
    entities[name] = {x = 0, y = 0, width = 50, height = 50, vy = 0, hasGravity = withGravity or false}
  end,

  despawn = function(name)
    entities[name] = nil
  end,

  move = function(name, dx, dy)
    entities[name].x = entities[name].x + dx
    entities[name].y = entities[name].y + dy
  end,

  draw = function(name)
    local e = entities[name]
    if e then
      love.graphics.rectangle("fill", e.x, e.y, e.width, e.height)
    end
  end,

  setState = function(name, key, value)
    entities[name][key] = value
  end,

  getState = function(name, key)
    return entities[name][key]
  end,
}

local function applyGravity(dt)
  for name, e in pairs(entities) do
    if e.hasGravity then
      local g = handler.gravity
      for _, region in ipairs(regions) do
        if insideRegion(e, region.x, region.y, region.w, region.h) then
          g = region.gravity or g
        end
      end
      e.vy = (e.vy or 0) + g * dt
      e.y = e.y + e.vy
      if e.y + e.height >= 600 then
        e.y = 600 - e.height
        e.vy = 0
      end
    end
  end
end

function love.load()
${LuaEmitter.emitScript(world.setup, indent = 1)}
end

function love.update(dt)
  applyGravity(dt)
${LuaEmitter.emitScript(update, indent = 1)}
end

function love.draw()
  for _, region in ipairs(regions) do
    love.graphics.setColor(region.r, region.g, region.b, 0.3)
    love.graphics.rectangle("fill", region.x, region.y, region.w, region.h)
    love.graphics.setColor(1.0, 1.0, 1.0, 1.0)
  end
  for name, e in pairs(entities) do
    handler.draw(name)
  end
end""".stripMargin

  def writeToFile(world: World, update: Script, path: os.Path): Unit =
    val lua = wrap(world, update)
    os.makeDir.all(path / os.up)
    os.write.over(path, lua)

